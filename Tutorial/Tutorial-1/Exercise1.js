// Number
let p = 53;
console.log("Value of p:", p);
console.log("Type of p:", typeof p);

// String
let name = "ChatGPT";
console.log("Value of name:", name);
console.log("Type of name:", typeof name);

// Boolean
let isLearning = true;
console.log("Value of isLearning:", isLearning);
console.log("Type of isLearning:", typeof isLearning);

// Undefined
let x;
console.log("Value of x:", x);
console.log("Type of x:", typeof x);

// Null
let emptyValue = null;
console.log("Value of emptyValue:", emptyValue);
console.log("Type of emptyValue:", typeof emptyValue); // Note: typeof null is "object" (JavaScript quirk)

// Object
let person = { firstName: "Alice", age: 25 };
console.log("Value of person:", person);
console.log("Type of person:", typeof person);

// Array
let numbers = [1, 2, 3, 4, 5];
console.log("Value of numbers:", numbers);
console.log("Type of numbers:", typeof numbers); // Arrays are technically objects

// Function
function greet() {
  return "Hello, World!";
}
console.log("Value of greet:", greet);
console.log("Type of greet:", typeof greet);
